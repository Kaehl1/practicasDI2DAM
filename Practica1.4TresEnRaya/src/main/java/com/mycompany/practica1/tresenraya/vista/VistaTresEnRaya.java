    public void pintarCasilla(int fila, int columna, Color color){
        JButton boton = botones[fila][columna];
        boton.setBackground(color);
        boton.setOpaque(true);
        boton.setBorderPainted(false);
        boton.setEnabled(false);
    }
    
    public void reiniciarTablero(){
        for(int i = 0; i < 3; i++){
            for(int j = 0; j < 3; j++){
                botones[i][j].setEnabled(true);
                botones[i][j].setBackground(null);
                botones[i][j].setBorderPainted(true);
                botones[i][j].setText("");
            }
        }
    }
    
    public void addCasillasListener(ActionListener l){
        for(int i = 0; i < 3; i++){
            for(int j = 0; j < 3; j++){
                botones[i][j].addActionListener(l);
            }
        }
    }
    
